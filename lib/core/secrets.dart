const String _saltBase64 = 'fT2JQQzNMJl2NRoMbo9RjA==';

final Uint8List _salt = base64Decode(_saltBase64);

class _Blowfish {
  final List<int> _p = List<int>.from(_pOrig);
  final List<int> _s = List<int>.from(_sOrig);

  static int _wordAt(Uint8List data, int offset) {
    var num = 0;
    for (var i = 0; i < 4; i++) {
      num = (num << 8) | (data[(offset + i) % data.length] & 0xff);
    }
    return num & 0xffffffff;
  }

  void _encipher(List<int> block, int offset) {
    var l = block[offset];
    var r = block[offset + 1];
    l ^= _p[0];
    var i = 0;
    while (i <= 14) {
      var n =
          (_s[(l >> 24) & 0xff] + _s[0x100 | ((l >> 16) & 0xff)]) & 0xffffffff;
      n = (n ^ _s[0x200 | ((l >> 8) & 0xff)]) & 0xffffffff;
      n = (n + _s[0x300 | (l & 0xff)]) & 0xffffffff;
      r ^= n ^ _p[++i];
      n = (_s[(r >> 24) & 0xff] + _s[0x100 | ((r >> 16) & 0xff)]) & 0xffffffff;
      n = (n ^ _s[0x200 | ((r >> 8) & 0xff)]) & 0xffffffff;
      n = (n + _s[0x300 | (r & 0xff)]) & 0xffffffff;
      l ^= n ^ _p[++i];
    }
    block[offset] = r ^ _p[17];
    block[offset + 1] = l;
  }

  void _key(Uint8List key) {
    var offset = 0;
    final block = List<int>.filled(2, 0);
    final pLen = _p.length;
    final sLen = _s.length;
    for (var i = 0; i < pLen; i++) {
      _p[i] ^= _wordAt(key, offset);
      offset = (offset + 4) % key.length;
    }
    for (var i = 0; i < pLen; i += 2) {
      _encipher(block, 0);
      _p[i] = block[0];
      _p[i + 1] = block[1];
    }
    for (var i = 0; i < sLen; i += 2) {
      _encipher(block, 0);
      _s[i] = block[0];
      _s[i + 1] = block[1];
    }
  }

  void _eksKey(Uint8List salt, Uint8List input) {
    var offset = 0;
    var offset2 = 0;
    final block = List<int>.filled(2, 0);
    final pLen = _p.length;
    final sLen = _s.length;
    for (var i = 0; i < pLen; i++) {
      _p[i] ^= _wordAt(input, offset);
      offset = (offset + 4) % input.length;
    }
    for (var i = 0; i < pLen; i += 2) {
      block[0] ^= _wordAt(salt, offset2);
      offset2 = (offset2 + 4) % salt.length;
      block[1] ^= _wordAt(salt, offset2);
      offset2 = (offset2 + 4) % salt.length;
      _encipher(block, 0);
      _p[i] = block[0];
      _p[i + 1] = block[1];
    }
    for (var i = 0; i < sLen; i += 2) {
      block[0] ^= _wordAt(salt, offset2);
      offset2 = (offset2 + 4) % salt.length;
      block[1] ^= _wordAt(salt, offset2);
      offset2 = (offset2 + 4) % salt.length;
      _encipher(block, 0);
      _s[i] = block[0];
      _s[i + 1] = block[1];
    }
  }

  Uint8List cryptRaw(Uint8List input, Uint8List salt, int workFactor) {
    final ctext = List<int>.from(_bfCryptCiphertext);
    final count = ctext.length;
    final rounds = 1 << workFactor;
    _eksKey(salt, input);
    for (var i = 0; i < rounds; i++) {
      _key(input);
      _key(salt);
    }
    for (var i = 0; i < 64; i++) {
      for (var j = 0; j < count >> 1; j++) {
        _encipher(ctext, j << 1);
      }
    }
    final out = Uint8List(count * 4);
    var o = 0;
    for (var i = 0; i < count; i++) {
      out[o++] = (ctext[i] >> 24) & 0xff;
      out[o++] = (ctext[i] >> 16) & 0xff;
      out[o++] = (ctext[i] >> 8) & 0xff;
      out[o++] = ctext[i] & 0xff;
    }
    return out;
  }
}

/// Mirrors Terraria.Utilities.Secrets.ToSecret.
String toSecret(String plainInput) {
  var bytes = Uint8List.fromList(utf8.encode(plainInput));
  bytes = _Blowfish().cryptRaw(bytes, _salt, 4);
  for (var i = 0; i < 1000; i++) {
    final a = i % bytes.length;
    final b = bytes[a] % bytes.length;
    final tmp = bytes[a];
    bytes[a] = bytes[b];
    bytes[b] = tmp;
  }
  bytes = _Blowfish().cryptRaw(bytes, _salt, 4);
  return base64Encode(bytes);
}

